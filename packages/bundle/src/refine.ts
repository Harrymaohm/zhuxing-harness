/** 明显无需精炼的输入（寒暄、确认、单字）：零成本挡在模型调用之前。 */
const SMALLTALK_RE =
  /^(你好|您好|hi|hello|嗨|哈喽|在吗|在么|谢谢|多谢|thanks|thank you|ok|okay|好的|好|收到|嗯|嗯嗯|是的|对|继续|go on|test|测试)[\s!！。.~～?？,，]*$/i

export function looksLikeSmalltalk(input: string): boolean {
  const t = input.trim()
  return t.length <= 12 && SMALLTALK_RE.test(t)
}

/**
 * 任务书结构校验（确定性护栏，不依赖模型自觉）。
 *
 * 实测退化形态：对已经写清楚的指令，精炼器会把整份任务书压成一句结论
 * （如「执行步骤：循环上界应为 <= n」）。主循环读到「结论已知」，就谎报改完、
 * 一次工具都不调用——比不做精炼更糟。这类输出必须丢弃、退回原始指令。
 */
export function isStructuredBrief(text: string): boolean {
  if (text.length < 80) return false
  const headings = text.match(/^#{1,3}\s+\S+/gm) ?? []
  return headings.length >= 2
}
